export function zoneVon(w: Welt): string {
  const tz = w.env.TZ ?? w.vars.TZ;
  if (tz !== undefined) return tz.replace(/^:/, '') || 'UTC';
  const l = w.fs['/etc/localtime'] ?? '';
  return l.startsWith('-> ') ? l.slice(3).replace(/^\/usr\/share\/zoneinfo\//, '') : 'UTC';
}
const zz = (n: number) => String(n).padStart(2, '0');
export function datumFormat(w: Welt, ms: number, fmt?: string, utc = false): string {
  const zone = utc ? 'UTC' : zoneVon(w);
  const [off, abk] = ZONEN[zone] ?? [0, zone.match(/^[A-Z]{3,5}/)?.[0] ?? 'UTC'];
  const d = new Date(ms + off * 3600000);
  const lang = w.env.LC_ALL || w.env.LC_TIME || w.env.LANG || w.vars.LANG || 'C';
  const de = /^de/.test(lang);
  const Y = d.getUTCFullYear(), m = d.getUTCMonth(), t = d.getUTCDate(), H = d.getUTCHours(), M = d.getUTCMinutes(), S = d.getUTCSeconds(), wt = d.getUTCDay();
  const z = (off >= 0 ? '+' : '-') + zz(Math.floor(Math.abs(off))) + zz(Math.round((Math.abs(off) % 1) * 60));
  if (fmt === undefined) return de ? `${TAGE[wt]} ${t}. ${MON[m]} ${zz(H)}:${zz(M)}:${zz(S)} ${abk} ${Y}` : `${TAGE_EN[wt]} ${MON_EN[m]} ${String(t).padStart(2, ' ')} ${zz(H)}:${zz(M)}:${zz(S)} ${abk} ${Y}`;
  return fmt.replace(/%([YmdHMSFTZzaAbBsjuyeDR%n])/g, (_, c) => ({
    Y: String(Y), m: zz(m + 1), d: zz(t), H: zz(H), M: zz(M), S: zz(S), F: `${Y}-${zz(m + 1)}-${zz(t)}`, T: `${zz(H)}:${zz(M)}:${zz(S)}`, R: `${zz(H)}:${zz(M)}`,
    Z: abk, z, a: (de ? TAGE : TAGE_EN)[wt], A: (de ? TAGE_LANG : TAGE_LANG_EN)[wt], b: (de ? MON : MON_EN)[m], B: (de ? MON_LANG : MON_LANG_EN)[m],
    s: String(Math.floor(ms / 1000)), j: String(Math.floor((Date.UTC(Y, m, t) - Date.UTC(Y, 0, 0)) / 86400000)).padStart(3, '0'), u: String(wt || 7), y: zz(Y % 100), e: String(t).padStart(2, ' '), D: `${zz(m + 1)}/${zz(t)}/${zz(Y % 100)}`, '%': '%', n: '\n',
  } as Record<string, string>)[c]);
}

// ---------- cron ----------

const CRON_NAMEN = /^(@(reboot|yearly|annually|monthly|weekly|daily|midnight|hourly)\s+\S|[A-Za-z_]\w*\s*=)/;
const FELDER: [string, number, number, RegExp?][] = [['minute', 0, 59], ['hour', 0, 23], ['day-of-month', 1, 31], ['month', 1, 12, /^(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)$/i], ['day-of-week', 0, 7, /^(sun|mon|tue|wed|thu|fri|sat)$/i]];
function feldOk(f: string, min: number, max: number, namen?: RegExp) {
  return f.split(',').every((teil) => {
    const [bereich, schritt] = teil.split('/');
    if (schritt !== undefined && !/^\d+$/.test(schritt)) return false;
    if (bereich === '*') return true;
    const grenzen = bereich.split('-');
    if (grenzen.length > 2) return false;
    return grenzen.every((g) => (namen?.test(g) ?? false) || (/^\d+$/.test(g) && +g >= min && +g <= max));
  });
}
export function cronPruefen(text: string, mitUser: boolean): string[] {
  const fehlerListe: string[] = [];
  text.split('\n').forEach((z, i) => {
    const t = z.trim();
    if (!t || t.startsWith('#') || CRON_NAMEN.test(t)) return;
    const f = t.split(/\s+/);
    if (f.length < (mitUser ? 7 : 6)) { fehlerListe.push(`"-":${i + 1}: bad ${FELDER[Math.min(f.length, 4)]?.[0] ?? 'command'}`); return; }
    for (let k = 0; k < 5; k++) if (!feldOk(f[k], FELDER[k][1], FELDER[k][2], FELDER[k][3])) { fehlerListe.push(`"-":${i + 1}: bad ${FELDER[k][0]}`); return; }
  });
  return fehlerListe;
}
function cronErlaubt(w: Welt, user: string): boolean {
  if (user === 'root') return true;
  const liste = (p: string) => (w.fs[p] ?? '').split('\n').map((x) => x.trim()).filter(Boolean);
  if ('/etc/cron.allow' in w.fs) return liste('/etc/cron.allow').includes(user);
  if ('/etc/cron.deny' in w.fs) return !liste('/etc/cron.deny').includes(user);
  return true;
}
function atErlaubt(w: Welt, user: string): boolean {
  if (user === 'root') return true;
  const liste = (p: string) => (w.fs[p] ?? '').split('\n').map((x) => x.trim()).filter(Boolean);
  if ('/etc/at.allow' in w.fs) return liste('/etc/at.allow').includes(user);
  if ('/etc/at.deny' in w.fs) return !liste('/etc/at.deny').includes(user);
  return false;
}
function cronInstallieren(w: Welt, user: string, text: string): Ergebnis {
  const f = cronPruefen(text, false);
  if (f.length) return fehler(`${f.join('\n')}\nerrors in crontab file, can't install.`);
  const p = `/var/spool/cron/crontabs/${user}`;
  w.fs[p] = text.endsWith('\n') || !text ? text : text + '\n';
  K.rechte(w, p, 0o600, user, 'crontab');
  return ok();
}

