interface AtJob { nr: number; zeit: number; user: string; befehle: string; queue: string }
interface ZeitStand { atJobs: AtJob[]; atNr: number; timer: Record<string, { aktiv: boolean; enabled: boolean }>; runNr: number }
function zs(w: Welt): ZeitStand {
  const x = w as Welt & { zeit?: ZeitStand };
  if (!x.zeit) x.zeit = { atJobs: [], atNr: 1, timer: {}, runNr: 4711 };
  return x.zeit;
}
