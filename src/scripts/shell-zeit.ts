function atZeit(w: Welt, spec: string): number | null {
  const jetzt = w.uhr; const [off] = ZONEN[zoneVon(w)] ?? [0];
  const lokal = (ms: number) => new Date(ms + off * 3600000);
  const ab = (h: number, mi: number, plusTage = 0) => { const d = lokal(jetzt); let t = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate() + plusTage, h, mi) - off * 3600000; if (t <= jetzt && !plusTage) t += 86400000; return t; };
  const s = spec.trim().toLowerCase();
  let m;
  if ((m = s.match(/^now(?:\s*\+\s*(\d+)\s*(min|minute|minutes|hour|hours|day|days|week|weeks))?$/))) { const n = Number(m[1] ?? 0); const u = m[2] ?? 'min'; return jetzt + n * (u.startsWith('min') ? 60000 : u.startsWith('hour') ? 3600000 : u.startsWith('day') ? 86400000 : 604800000); }
  const zusatz = s.match(/\s+(tomorrow)$/); const kern = s.replace(/\s+tomorrow$/, '');
  const plus = zusatz ? 1 : 0;
  if (kern === 'noon') return ab(12, 0, plus); if (kern === 'midnight') return ab(0, 0, plus || 1); if (kern === 'teatime') return ab(16, 0, plus);
  if (kern === 'tomorrow') return jetzt + 86400000;
  if ((m = kern.match(/^(\d{1,2}):?(\d{2})?\s*(am|pm)?$/))) { let h = Number(m[1]); const mi = Number(m[2] ?? 0); if (m[3] === 'pm' && h < 12) h += 12; if (m[3] === 'am' && h === 12) h = 0; if (h > 23 || mi > 59) return null; return ab(h, mi, plus); }
  if ((m = kern.match(/^(\d{1,2}):(\d{2})\s+(\d{4})-(\d{2})-(\d{2})$/))) return Date.UTC(+m[3], +m[4] - 1, +m[5], +m[1], +m[2]) - off * 3600000;
  return null;
}

